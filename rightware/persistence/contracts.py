"""Structural interfaces shared by the local SQLite and PostgreSQL stores."""
from __future__ import annotations   # SYNC-INFRA01: lazy annotations (a method named `list` shadowed `list[...]`)

from typing import Protocol
from rightware.memory.store import Memory
from rightware.knowledge.store import Doc, Hit
from rightware.knowledge.ingest import Extracted

class MemoryRepository(Protocol):
    def add(self, owner: str, category: str, topic: str, content: str, provenance: dict) -> tuple[Memory, list[str]]: ...
    def update(self, owner: str, mid: str, content: str, provenance: dict) -> Memory | None: ...
    def delete(self, owner: str, mid: str) -> bool: ...
    def get(self, owner: str, mid: str) -> Memory | None: ...
    def active(self, owner: str) -> list[Memory]: ...
    def events(self, owner: str) -> list[tuple]: ...

class KnowledgeRepository(Protocol):
    def add(self, owner: str, ex: Extracted, injection_suspected: bool) -> tuple[Doc, bool]: ...
    def get(self, owner: str, did: str) -> Doc | None: ...
    def list(self, owner: str) -> list[Doc]: ...
    def delete(self, owner: str, did: str) -> bool: ...
    def segments(self, owner: str, did: str, first: int = 0, limit: int = 4) -> list[Hit]: ...
    def by_locator(self, owner: str, did: str, locator_prefix: str) -> list[Hit]: ...
    def search(self, owner: str, query: str, doc_ids: list[str] | None = None, k: int = 6) -> list[Hit]: ...
