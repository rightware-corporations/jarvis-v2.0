"""WORK-07 R3-C2-012 — E1 + E4: deterministic completion-interception feasibility. TEST-ONLY.

NOT a production completion controller. It answers one question: can the EXISTING
``_GuardedEngine`` boundary intercept a premature final answer, request a BOUNDED continuation,
and keep every RIGHTWARE tool control (policy, audit, quotas, anti-loop, cancel, deadline)?

* ``InterceptingEngine`` subclasses the real ``rightware.agent.session._GuardedEngine`` and is
  installed only for the duration of an experiment (``installed()``), by replacing the module
  attribute that ``AgentSession.run`` looks up. Production ``run()`` and ``_compose()`` are untouched.
* Objectives are GIVEN by the experiment (required page URLs). Where objectives come from (E3)
  is out of scope.
* The completion check reads only code-recorded evidence: browser events with outcome OK.
* Feedback is generated by code from objective ids/labels: never page text.
* Every model generation is counted (``CountingEngine``), including those the orchestrator's
  ``max_turns`` does not see. The continuation budget never resets policy budgets.

Results are FAKE-model evidence about the RIGHTWARE plumbing, never about Qwen.
"""
from __future__ import annotations

import contextlib
import dataclasses


FEEDBACK_TAG = "[RIGHTWARE-VERIFICAÇÃO]"


@dataclasses.dataclass(frozen=True)
class Objective:
    oid: str
    label: str            # shown to the model (code-generated, no page text)
    required_url: str     # evidence: a browser event with outcome OK at this final URL


class CountingEngine:
    """Ground truth for E4: counts every call that reaches the model."""

    def __init__(self, engine):
        self._engine = engine
        self.engine_id = getattr(engine, "engine_id", "")
        self.calls = 0

    def generate(self, messages, **kwargs):
        self.calls += 1
        return self._engine.generate(messages, **kwargs)


@dataclasses.dataclass
class ExperimentState:
    objectives: tuple = ()
    budget: int = 1
    continuations: int = 0                # extra generations requested by the interceptor
    orchestrator_generations: int = 0     # generations requested by the orchestrator loop
    verdict: str = "NOT_EVALUATED"        # COMPLETE_VERIFIED | INCOMPLETE_BUDGET_EXHAUSTED | HALTED | NO_FINAL_ANSWER
    missing: list = dataclasses.field(default_factory=list)
    feedback_sent: list = dataclasses.field(default_factory=list)
    events: list = dataclasses.field(default_factory=list)


def missing_objectives(session, objectives) -> list:
    """Deterministic: an objective is met only by a code-recorded OK page load at its URL."""
    browser = session.browser
    opened = {e.get("final_url") for e in (browser.events if browser else []) if e.get("outcome") == "OK"}
    return [o for o in objectives if o.required_url not in opened]


def feedback_text(missing) -> str:
    items = "; ".join(f"{o.oid}: {o.label}" for o in missing)
    return (f"{FEEDBACK_TAG} A resposta ainda não pode ser dada como concluída. Objectivos sem evidência de "
            f"execução: {items}. Usa as ferramentas autorizadas para os cumprir, ou explica porque não é possível.")


def make_intercepting_engine(base_cls, session, state: ExperimentState):
    from openjarvis.core.types import Message, Role

    class InterceptingEngine(base_cls):
        def generate(self, messages, **kwargs):
            state.orchestrator_generations += 1
            result = self._attempt(messages, kwargs)
            while not result.get("tool_calls"):
                if self.halted is not None:                     # halt short-circuit: terminal
                    state.verdict = "HALTED"
                    state.events.append(("halted", self.halted))
                    return result
                missing = missing_objectives(session, state.objectives)
                if not missing:
                    state.verdict, state.missing = "COMPLETE_VERIFIED", []
                    return result
                state.missing = [o.oid for o in missing]
                if state.continuations >= state.budget:
                    state.verdict = "INCOMPLETE_BUDGET_EXHAUSTED"
                    state.events.append(("budget_exhausted", state.missing))
                    return result
                if self._policy.halt_reason:                    # never re-prompt after cancel/deadline/budget
                    self.halted = self._policy.halt_reason
                    state.verdict = "HALTED"
                    state.events.append(("halted_before_continuation", self.halted))
                    return result
                state.continuations += 1
                text = feedback_text(missing)
                state.feedback_sent.append(text)
                state.events.append(("continuation", state.missing))
                messages.append(Message(role=Role.ASSISTANT, content=result.get("content", "") or ""))
                messages.append(Message(role=Role.USER, content=text))
                result = self._attempt(messages, kwargs)
            state.verdict = "IN_PROGRESS"
            return result

        def _attempt(self, messages, kwargs):
            return super().generate(messages, **kwargs)     # real halt/batch/trace logic, unchanged

    return InterceptingEngine


@contextlib.contextmanager
def installed(session, state: ExperimentState):
    """Swap the module attribute used by AgentSession.run for this experiment only."""
    from rightware.agent import session as S
    original = S._GuardedEngine
    S._GuardedEngine = make_intercepting_engine(original, session, state)
    try:
        yield
    finally:
        S._GuardedEngine = original
